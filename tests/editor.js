const form = document.querySelector('form');
const submit = () => form.dispatchEvent(new window.Event('submit', {cancelable:true}));
submit();
const hidden = () => [...document.querySelector('#marclandtrust-serialized').children];
const value = name => hidden().find(input => input.name === name)?.value;
assert.equal(form.enctype, 'multipart/form-data');
assert.equal(fileInput.name, 'trust_icons[0]'); assert.equal(fileInput.disabled, false);
