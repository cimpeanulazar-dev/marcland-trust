const fs = require('node:fs');
const assert = require('node:assert/strict');
const {JSDOM} = require('jsdom');
const dom = new JSDOM(fs.readFileSync(process.argv[2], 'utf8'), {runScripts: 'outside-only'});
const {window} = dom;
window.eval(fs.readFileSync(require('node:path').join(__dirname, '../views/js/admin-config.js'), 'utf8'));
window.document.dispatchEvent(new window.Event('DOMContentLoaded'));
const document = window.document;
const change = element => element.dispatchEvent(new window.Event('change', {bubbles:true}));
const cards = () => [...document.querySelector('#marclandtrust-items').children];
const original = cards()[0];
const text = original.querySelector('[data-field="text"]');
text.value = 'Edited Romanian 🚚'; text.dispatchEvent(new window.Event('input'));
const language = document.querySelector('#marclandtrust-language');
language.value = '29'; change(language);
